function makeSubject(department, semesterNumber, title, bnTitle, index, custom = false) {
  const departmentIndex = departments.findIndex((entry) => entry.id === department.id);
  const price = (departmentIndex + semesterNumber + index) % 7 === 0
    ? 0
    : custom ? 80 : 50 + ((departmentIndex * 13 + semesterNumber * 7 + index * 11) % 70);
  return {
    id: `${department.id}-${semesterNumber}-${custom ? "custom" : `starter-${index}`}-${index}`,
    title,
    bnTitle,
    subject: `${department.name} · ${semesterNames[semesterNumber - 1]} semester study notes`,
    bnSubject: `${department.bnName} · ${semesterBnNames[semesterNumber - 1]} পর্বের পড়ার নোট`,
    overview: `An editable starter overview for ${title}. Add the verified syllabus, chapter list, and learning outcomes from the Admin catalogue.`,
    bnOverview: `${title} বিষয়টির জন্য সম্পাদনাযোগ্য প্রাথমিক পরিচিতি। অ্যাডমিন ক্যাটালগ থেকে যাচাইকৃত সিলেবাস, অধ্যায় ও শেখার লক্ষ্য যোগ করুন।`,
    department: department.id,
    semester: semesterNumber,
    price,
    icon: department.icon,
    tint: tints[index % tints.length],
    driveUrl: "",
    isStarter: !custom,
  };
}

export function createStarterSubjects() {
  return departments.flatMap((department) =>
    semesters.flatMap(({ number }, semesterIndex) => {
      const foundation = foundationSubjects[semesterIndex].map(([title, bnTitle], index) =>
        makeSubject(department, number, title, bnTitle, index),
      );
      const specialtyTitle = `${department.focus}: ${specialties[department.id][semesterIndex]}`;
      const specialtyBnTitle = `${department.bnFocus}: ${specialties[department.id][semesterIndex]}`;
      return [...foundation, makeSubject(department, number, specialtyTitle, specialtyBnTitle, 3)];
    }),
  );
}

export function createSemesterCourses(subjects) {
  return departments.flatMap((department, departmentIndex) =>
    semesters.flatMap(({ number, label, bnLabel }) => {
      const includedSubjects = subjects.filter(
        (subject) => subject.department === department.id && subject.semester === number,
      );
      if (includedSubjects.length === 0) return [];
      return [{
        id: `${department.id}-semester-${number}`,
        title: `${department.name} · ${label} Semester Study Pack`,
        bnTitle: `${department.bnName} · ${bnLabel} পর্বের স্টাডি প্যাক`,
        description: `A semester-wise learning pack with ${includedSubjects.length} subject guides for ${department.name}.`,
        bnDescription: `${department.bnName} বিভাগের ${includedSubjects.length}টি বিষয়ের গাইডসহ সেমিস্টারভিত্তিক স্টাডি প্যাক।`,
        department: department.id,
        semester: number,
        price: 250 + ((departmentIndex + number) % 8) * 25,
        duration: `${label} semester`,
        icon: department.icon,
        subjects: includedSubjects,
      }];
    }),
  );
}

export function loadSavedSubjects() {
  try {
    const saved = window.localStorage.getItem("dth-subject-catalog");
    if (!saved) return createStarterSubjects();
    const parsed = JSON.parse(saved);
    if (!Array.isArray(parsed) || !parsed.every(isCatalogSubject)) {
      throw new TypeError("Saved DTH subject catalogue has an invalid format.");
    }
    return parsed;
  } catch (error) {
    console.error("Could not load the saved DTH subject catalogue.", error);
    return createStarterSubjects();
  }
}

export function isCatalogSubject(subject) {
  const validDriveLink = (value) => {
    if (value === "") return true;
    try {
      const url = new URL(value);
      return url.protocol === "https:" &&
        (url.hostname === "drive.google.com" || url.hostname === "docs.google.com");
    } catch {
      return false;
    }
  };
  return Boolean(
    subject &&
    typeof subject.id === "string" &&
    typeof subject.title === "string" &&
    subject.title.trim().length > 0 &&
    typeof subject.bnTitle === "string" &&
    subject.bnTitle.trim().length > 0 &&
    typeof subject.overview === "string" &&
    typeof subject.bnOverview === "string" &&
    departments.some((department) => department.id === subject.department) &&
    Number.isInteger(subject.semester) &&
    subject.semester >= 1 &&
    subject.semester <= 8 &&
    Number.isSafeInteger(subject.price) &&
    subject.price >= 0 &&
    typeof subject.icon === "string" &&
    typeof subject.tint === "string" &&
    typeof subject.driveUrl === "string" &&
    validDriveLink(subject.driveUrl),
  );
}

